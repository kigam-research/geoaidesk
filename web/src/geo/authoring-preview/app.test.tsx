import { act, fireEvent, render, screen, waitFor, cleanup } from "@testing-library/react";
import { afterEach, beforeEach, expect, it, vi } from "vitest";
import type { PreviewSourceInputProps, PreviewSourcePaneProps, PreviewMethodProps } from "../contracts/authoring-preview";
const mocks = vi.hoisted(() => ({ fetch: vi.fn(), revoke: vi.fn(), create: vi.fn(() => "blob:local-pdf") }));
vi.mock("./source-input", () => ({ MAX_PREVIEW_PDF_BYTES: 50 * 1024 * 1024, PreviewSourceInput: (p: PreviewSourceInputProps) => <><button onClick={p.onSample}>Sample</button><button onClick={() => p.onPdfFile(new File(["%PDF-fixture"], "local.pdf", { type: "application/pdf" }))}>Local PDF</button><button onClick={p.onClear}>Clear source</button></> }));
vi.mock("./source-pane", () => ({ PreviewSourcePane: (p: PreviewSourcePaneProps) => <div><span>{p.source?.name}</span><span>{p.sourceUrl}</span><button onClick={() => p.onPdfReady?.(36)}>PDF ready</button></div> }));
vi.mock("./method-pane", () => ({ PreviewMethodPane: (p: PreviewMethodProps) => <div>Prepared findings<button onClick={() => p.onEvent({ type: "choice", value: "draft-code" })}>Choose draft</button><button onClick={() => p.onEvent({ type: "create-draft" })}>Create draft</button></div> }));
vi.mock("./trial-pane", () => ({ PreviewTrialPane: (p: PreviewMethodProps) => <div>Untested draft: {p.state.draft?.title}</div> }));
vi.mock("./preview-dialogs", () => ({ PreviewDialogs: () => null }));
import { AuthoringPreview } from "./app";
import { PREVIEW_STORAGE_KEY } from "./state";
beforeEach(() => { localStorage.clear(); localStorage.setItem("gaid:locale", "en"); vi.stubGlobal("fetch", mocks.fetch); vi.stubGlobal("URL", class extends URL { static createObjectURL = mocks.create; static revokeObjectURL = mocks.revoke; }); });
afterEach(() => { cleanup(); vi.unstubAllGlobals(); vi.clearAllMocks(); });
it("rejects a stale sample response after the researcher selects a different PDF", async () => {
  let resolve!: (value: { ok: boolean }) => void;
  mocks.fetch.mockReturnValueOnce(new Promise((r) => { resolve = r; }));
  render(<AuthoringPreview />);
  fireEvent.click(screen.getByText("Sample"));
  fireEvent.click(screen.getByText("Local PDF"));
  await act(async () => resolve({ ok: true }));
  expect(screen.getByText("local.pdf")).toBeInTheDocument();
  fireEvent.click(screen.getByText("PDF ready"));
  expect(screen.getByRole("button", { name: "View prepared analysis example" })).toBeDisabled();
  expect(screen.queryByText("Prepared findings")).not.toBeInTheDocument();
  fireEvent.click(screen.getByText("Clear source"));
  expect(mocks.revoke).toHaveBeenCalledWith("blob:local-pdf");
});
it("opens prepared findings only after the real sample is ready, saves metadata and resets only its own key", async () => {
  mocks.fetch.mockResolvedValue({ ok: true });
  localStorage.setItem("unrelated-project", "keep");
  render(<AuthoringPreview />);
  fireEvent.click(screen.getByText("Sample"));
  await screen.findByText("Yilgarn Ni · author manuscript");
  expect(screen.getByRole("button", { name: "View prepared analysis example" })).toBeDisabled();
  fireEvent.click(screen.getByText("PDF ready"));
  fireEvent.click(screen.getByRole("button", { name: "View prepared analysis example" }));
  expect(screen.getByText("Prepared findings")).toBeInTheDocument();
  fireEvent.click(screen.getByText("Choose draft")); fireEvent.click(screen.getByText("Create draft"));
  fireEvent.click(screen.getByRole("button", { name: "Save in browser" }));
  await waitFor(() => expect(JSON.parse(localStorage.getItem(PREVIEW_STORAGE_KEY)!).draft).not.toBeNull());
  expect(localStorage.getItem(PREVIEW_STORAGE_KEY)).not.toContain("blob:");
  fireEvent.click(screen.getByRole("button", { name: "Reset prototype" }));
  expect(localStorage.getItem(PREVIEW_STORAGE_KEY)).toBeNull();
  expect(localStorage.getItem("unrelated-project")).toBe("keep");
});
it("keeps saved choices and edited draft accessible when the sample asset is unavailable", async () => {
  const { initialPreviewState, SAMPLE_REFERENCE } = await import("./state");
  localStorage.setItem(PREVIEW_STORAGE_KEY, JSON.stringify({ ...initialPreviewState(), source: { kind: "sample", name: "Paper", reference: SAMPLE_REFERENCE }, exampleAnalysis: true, choice: "draft-code", step: "trial", draft: { title: "My saved method", summary: "My notes" } }));
  mocks.fetch.mockResolvedValue({ ok: false });
  render(<AuthoringPreview />);
  await screen.findByText(/Could not open the sample manuscript/);
  expect(screen.getByText("Untested draft: My saved method")).toBeInTheDocument();
  fireEvent.click(screen.getByRole("button", { name: "Save in browser" }));
  expect(JSON.parse(localStorage.getItem(PREVIEW_STORAGE_KEY)!).draft.title).toBe("My saved method");
});
